void cn_draw_char(uint32_t utf8_code, uint32_t x, uint32_t y, uint32_t fg_color, uint32_t bg_color) {
    cn_draw_char_impl(utf8_code, x, y, fg_color, bg_color);
}

/*
 * cn_draw_text - 绘制中文文本
 * @text: UTF-8 编码的文本
 * @x, @y: 起始坐标
 * @fg_color: 前景色
 * @bg_color: 背景色
 */
void cn_draw_text(const char *text, uint32_t x, uint32_t y, uint32_t fg_color, uint32_t bg_color) {
    if (!text) return;
    
    uint32_t cur_x = x;
    
    while (*text) {
        int bytes_read = 0;
        uint32_t code = utf8_decode(text, &bytes_read);
        
        if (bytes_read == 0) break;
        
        /* 检查是否为中文字符 */
        if (is_utf8_chinese_start((uint8_t)text[0])) {
            /* 绘制中文字符 */
            cn_draw_char(code, cur_x, y, fg_color, bg_color);
            cur_x += CN_CHAR_WIDTH;
        } else {
            /* ASCII 字符, 由 console.c 的 draw_char 处理 */
            /* 这里简单跳过, 实际应由调用者处理混合文本 */
            cur_x += 6; /* 假设 ASCII 宽度 */
        }
        
        text += bytes_read;
    }
}
