/*
 * utf8_decode - 解码 UTF-8 字符
 * @str: UTF-8 编码的字符串指针
 * @bytes_read: 输出参数, 返回读取的字节数
 * 
 * 返回: Unicode 码点
 */
uint32_t utf8_decode(const char *str, int *bytes_read) {
    uint8_t b0, b1, b2, b3;
    uint32_t code;
    
    if (!str || !bytes_read) {
        if (bytes_read) *bytes_read = 0;
        return 0;
    }
    
    b0 = (uint8_t)str[0];
    
    /* ASCII 字符 (0xxxxxxx) */
    if ((b0 & 0x80) == 0x00) {
        *bytes_read = 1;
        return (uint32_t)b0;
    }
    
    /* 2 字节字符 (110xxxxx 10xxxxxx) */
    if ((b0 & 0xE0) == 0xC0) {
        b1 = (uint8_t)str[1];
        *bytes_read = 2;
        code = ((b0 & 0x1F) << 6) | (b1 & 0x3F);
        return code;
    }
    
    /* 3 字节字符 (1110xxxx 10xxxxxx 10xxxxxx) */
    if ((b0 & 0xF0) == 0xE0) {
        b1 = (uint8_t)str[1];
        b2 = (uint8_t)str[2];
        *bytes_read = 3;
        code = ((b0 & 0x0F) << 12) | ((b1 & 0x3F) << 6) | (b2 & 0x3F);
        return code;
    }
    
    /* 4 字节字符 (11110xxx 10xxxxxx 10xxxxxx 10xxxxxx) */
    if ((b0 & 0xF8) == 0xF0) {
        b1 = (uint8_t)str[1];
        b2 = (uint8_t)str[2];
        b3 = (uint8_t)str[3];
        *bytes_read = 4;
        code = ((b0 & 0x07) << 18) | ((b1 & 0x3F) << 12) | ((b2 & 0x3F) << 6) | (b3 & 0x3F);
        return code;
    }
    
    /* 无效字符 */
    *bytes_read = 1;
    return (uint32_t)'?';
}

/*
 * cn_font_find_char - 在字库中查找字符点阵
 * @utf8_code: UTF-8 编码 (3字节形式)
 * 
 * 返回: 点阵数据指针, 未找到返回 NULL
 */
const uint8_t* cn_font_find_char(uint32_t utf8_code) {
    for (int i = 0; i < cn_font_table_size; i++) {
        if (cn_font_table[i].utf8_code == utf8_code) {
            return cn_font_table[i].bitmap;
        }
    }
    return NULL;
}

