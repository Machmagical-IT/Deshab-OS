# 把 Linux 应用菜单和 Windows「开始菜单」扫成 SYSTEM/ESP/GUESTMENU.CNF。
# 桌面启动台读这个文件。Linux 来自 rootfs（以及 persist 上的 overlay upper）
# 的 *.desktop；Windows 来自 SYSTEM/WIN 里开始菜单的 .lnk。
param(
    [string]$RepoRoot = ""
)

$ErrorActionPreference = "Stop"
if (-not $RepoRoot) {
    $RepoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
}

$esp = Join-Path $RepoRoot "SYSTEM\ESP"
$outPath = Join-Path $esp "GUESTMENU.CNF"
$rootfs = Join-Path $esp "boot\linux-rootfs.img"
$persist = Join-Path $RepoRoot "SYSTEM\DATA\persist\deshab-persist.img"
$win = Join-Path $RepoRoot "SYSTEM\WIN"
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# GUESTMENU.CNF — generated by tools/desktop/scan_guest_menus.ps1")
$lines.Add("# L|name|label|/absolute/path|args")
$lines.Add("# W|name|label|X:\path\to\app.exe|args")
$seen = @{}

function Add-Guest([string]$kind, [string]$name, [string]$label, [string]$path, [string]$args) {
    if (-not $path) { return }
    $path = ($path -replace "\|", "/").Trim()
    if (-not $path) { return }
    $key = ($kind + "|" + $path).ToLowerInvariant()
    if ($seen.ContainsKey($key)) { return }
    $seen[$key] = $true
    $name = ($name -replace "\|", "").Trim()
    if ($name.Length -gt 11) { $name = $name.Substring(0, 11) }
    $label = (($label -replace "[\r\n\|]", " ") -replace "\s+", " ").Trim()
    if (-not $label) { $label = $name }
    if ($label.Length -gt 60) { $label = $label.Substring(0, 60) }
    $args = (($args -replace "[\r\n\|]", " ") -replace "\s+", " ").Trim()
    $lines.Add("$kind|$name|$label|$path|$args")
}

function Test-UninstallName([string]$name) {
    if (-not $name) { return $false }
    if ($name -match "卸载|Uninstall|卸载程序|Uninst") { return $true }
    return $false
}

# ---------- Windows 开始菜单 ----------
$winCount = 0
if (Test-Path -LiteralPath $win) {
    $shell = New-Object -ComObject WScript.Shell
    $roots = @()
    $common = Join-Path $win "ProgramData\Microsoft\Windows\Start Menu"
    if (Test-Path -LiteralPath $common) { $roots += $common }
    $users = Join-Path $win "Users"
    if (Test-Path -LiteralPath $users) {
        Get-ChildItem -LiteralPath $users -Directory -Force -ErrorAction SilentlyContinue | ForEach-Object {
            if ($_.Name -in @("All Users", "Default", "Default User", "Public")) { return }
            $sm = Join-Path $_.FullName "AppData\Roaming\Microsoft\Windows\Start Menu"
            if (Test-Path -LiteralPath $sm) { $roots += $sm }
        }
    }
    $seq = 0
    foreach ($root in $roots) {
        Get-ChildItem -LiteralPath $root -Recurse -Filter *.lnk -File -Force -ErrorAction SilentlyContinue | ForEach-Object {
            if ($_.FullName -match "\\Startup\\|\\启动\\") { return }
            if (Test-UninstallName $_.BaseName) { return }
            $target = ""
            $arg = ""
            try {
                $sc = $shell.CreateShortcut($_.FullName)
                $target = [string]$sc.TargetPath
                $arg = [string]$sc.Arguments
            } catch {
                return
            }
            if (-not $target) { return }
            if (Test-UninstallName ([IO.Path]::GetFileNameWithoutExtension($target))) { return }
            $seq++
            $nm = "W{0:D3}" -f $seq
            if ($nm.Length -gt 11) { $nm = $nm.Substring(0, 11) }
            $before = $lines.Count
            Add-Guest "W" $nm $_.BaseName $target $arg
            if ($lines.Count -gt $before) { $script:winCount++ }
        }
    }
    Write-Host "[guest-menu] windows shortcuts=$winCount"
} else {
    Write-Host "[guest-menu] SYSTEM/WIN missing, skip windows"
}

# ---------- Linux .desktop ----------
$linuxCount = 0
if ((Test-Path -LiteralPath $rootfs) -and (Get-Command wsl -ErrorAction SilentlyContinue)) {
    $py = @'
import os, sys, stat, shlex

roots = [p for p in sys.argv[1:] if p and os.path.isdir(p)]

def parse(path):
    name = zh = exe = typ = None
    nodisplay = hidden = terminal = False
    entry = False
    try:
        f = open(path, "r", errors="replace")
    except OSError:
        return None
    with f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("["):
                entry = line == "[Desktop Entry]"
                continue
            if not entry or "=" not in line:
                continue
            k, v = line.split("=", 1)
            k, v = k.strip(), v.strip()
            if k == "Type":
                typ = v
            elif k == "Name":
                name = v
            elif k in ("Name[zh_CN]", "Name[zh]"):
                zh = v
            elif k == "Exec":
                exe = v
            elif k == "NoDisplay" and v.lower() == "true":
                nodisplay = True
            elif k == "Hidden" and v.lower() == "true":
                hidden = True
            elif k == "Terminal" and v.lower() == "true":
                terminal = True
    if nodisplay or hidden or terminal or not exe:
        return None
    if typ and typ != "Application":
        return None
    try:
        parts = shlex.split(exe)
    except ValueError:
        parts = exe.split()
    i = 0
    if parts and parts[0] == "env":
        i = 1
        while i < len(parts) and "=" in parts[i] and not parts[i].startswith("/"):
            i += 1
    if i >= len(parts):
        return None
    cmd = parts[i]
    args = []
    for a in parts[i + 1:]:
        if len(a) == 2 and a.startswith("%"):
            continue
        args.append(a)
    return (zh or name or "", cmd, " ".join(args))

def resolve(cmd):
    if not cmd or cmd.startswith("-"):
        return None
    if cmd.startswith("/"):
        for r in roots:
            if os.path.exists(os.path.join(r, cmd.lstrip("/"))):
                return cmd
        return cmd
    for sub in ("usr/bin", "usr/local/bin", "bin", "usr/sbin"):
        for r in roots:
            p = os.path.join(r, sub, cmd)
            if os.path.isfile(p):
                return "/" + sub + "/" + cmd
    return None

found = {}
order = []
for r in roots:
    for sub in ("usr/share/applications", "usr/local/share/applications"):
        base = os.path.join(r, sub)
        if not os.path.isdir(base):
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [d for d in dirnames if not d.startswith(".")]
            for fn in filenames:
                full = os.path.join(dirpath, fn)
                try:
                    st = os.lstat(full)
                except OSError:
                    continue
                if stat.S_ISCHR(st.st_mode) and st.st_rdev == 0:
                    found[fn] = None
                    continue
                if not fn.endswith(".desktop") or not stat.S_ISREG(st.st_mode):
                    continue
                parsed = parse(full)
                if fn not in order:
                    order.append(fn)
                found[fn] = parsed

def slug(cmd):
    base = os.path.basename(cmd).split(".")[0]
    out = []
    for ch in base:
        if ch.isascii() and (ch.isalnum() or ch in "_-"):
            out.append(ch)
        if len(out) >= 11:
            break
    return "".join(out) or "linux"

n = 0
for fn in order:
    item = found.get(fn)
    if not item:
        continue
    label, cmd, args = item
    path = resolve(cmd)
    if not path:
        continue
    name = slug(path)
    label = label.replace("|", " ").replace("\n", " ").strip() or name
    args = args.replace("|", " ")
    sys.stdout.write("L|%s|%s|%s|%s\n" % (name, label, path, args))
    n += 1
sys.stderr.write("[guest-menu] linux desktop=%d\n" % n)
'@
    $tmp = Join-Path $env:TEMP "deshab-scan-desktop.py"
    $utf8 = New-Object System.Text.UTF8Encoding $false
    [System.IO.File]::WriteAllText($tmp, ($py -replace "`r", ""), $utf8)
    $wslPy = "/mnt/" + $tmp.Substring(0, 1).ToLowerInvariant() + ($tmp.Substring(2) -replace "\\", "/")
    $wslRoot = ""
    $wslPersist = ""
    function To-Wsl([string]$p) {
        if ($p -match '^(?<d>[A-Za-z]):\\(?<rest>.*)$') {
            return "/mnt/" + $Matches['d'].ToLowerInvariant() + "/" + ($Matches['rest'] -replace "\\", "/")
        }
        return ""
    }
    $wslRoot = To-Wsl $rootfs
    if (Test-Path -LiteralPath $persist) { $wslPersist = To-Wsl $persist }
    $bash = @"
set -e
M1=/tmp/deshab-scan-root
M2=/tmp/deshab-scan-persist
cleanup() { umount "`$M1" 2>/dev/null || true; umount "`$M2" 2>/dev/null || true; }
trap cleanup EXIT
mkdir -p "`$M1" "`$M2"
mount -o loop,ro "$wslRoot" "`$M1"
ARGS="`$M1"
if [ -n "$wslPersist" ] && [ -f "$wslPersist" ]; then
  if mount -o loop,ro "$wslPersist" "`$M2"; then
    if [ -d "`$M2/deshab-rw" ]; then ARGS="`$ARGS `$M2/deshab-rw"; fi
  fi
fi
python3 "$wslPy" `$ARGS
"@
    $bash = $bash -replace "`r", ""
    $shPath = Join-Path $env:TEMP "deshab-scan-desktop.sh"
    [System.IO.File]::WriteAllText($shPath, $bash, $utf8)
    $wslSh = To-Wsl $shPath
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    $linuxOut = & wsl -u root -- bash $wslSh 2>&1
    $linuxRc = $LASTEXITCODE
    $ErrorActionPreference = $prev
    if ($linuxRc -ne 0) {
        Write-Host "[guest-menu] linux scan failed (rc=$linuxRc); windows entries kept"
        $linuxOut | Select-Object -Last 20 | ForEach-Object { Write-Host $_ }
    } else {
        foreach ($row in $linuxOut) {
            $t = [string]$row
            if ($t -match '^\[guest-menu\]') { Write-Host $t; continue }
            if ($t.StartsWith("L|")) {
                $lines.Insert(3 + $linuxCount, $t.Trim())
                $linuxCount++
            }
        }
        Write-Host "[guest-menu] linux lines=$linuxCount"
    }
} else {
    Write-Host "[guest-menu] linux rootfs or wsl missing, skip linux"
}

$dir = Split-Path -Parent $outPath
if (-not (Test-Path -LiteralPath $dir)) {
    New-Item -ItemType Directory -Path $dir | Out-Null
}
$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllLines($outPath, $lines.ToArray(), $utf8)
Write-Host "[guest-menu] wrote $outPath ($($lines.Count) lines)"
exit 0
